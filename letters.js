// 각 획은 중심선 점 목록. 획순은 배열 순서, 방향은 점 순서.
// joins: 손을 떼지 않고 다음 획으로 이어 써도 되는 획의 번호(0부터). 예: B의 두 굽은 획.
// ko: 글자 이름 한글 읽기, sound: 파닉스 소리, word/wordKo/meaning: 예시 단어와 읽기·뜻.

